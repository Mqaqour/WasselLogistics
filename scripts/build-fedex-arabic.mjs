// Generates components/shipping/fedexArabic.ts from the FedEx mapping JSON.
//
//   node scripts/build-fedex-arabic.mjs
//
// The source of truth is scripts/FedEx-mapping/fedex_master_mapping.json (clean
// UTF-8). Edit that file to add / fix translations, then re-run this script.
// The generated .ts holds plain object literals — no runtime JSON import.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, 'FedEx-mapping/fedex_master_mapping.json');
const OUT = resolve(__dirname, '../components/shipping/fedexArabic.ts');

const norm = (s) => String(s).normalize('NFKC').replace(/\s+/g, ' ').trim().toLowerCase();
const arOf = (e) => (e.customer_ar || e.arabic || '').trim();

const master = JSON.parse(readFileSync(SRC, 'utf8'));

// english (normalised) -> arabic. First writer wins, so order sections by how
// specific their phrasing is for a scan line.
const byEnglish = {};
const addEnglish = (list) => {
  for (const e of list || []) {
    const k = norm(e.english);
    const v = arOf(e);
    if (k && v && !(k in byEnglish)) byEnglish[k] = v;
  }
};
addEnglish(master.scan_events);
addEnglish(master.additional_tracking_statuses);
addEnglish(master.derived_statuses);
addEnglish(master.clearance_exceptions);
addEnglish(master.delivery_exceptions);
addEnglish(master.express_delivery_exceptions);

// scanEvents[].eventType -> arabic (scan_events wins over additional)
const byEventType = {};
for (const list of [master.additional_tracking_statuses, master.scan_events]) {
  for (const e of list || []) {
    const v = arOf(e);
    if (e.code && v) byEventType[e.code] = v; // scan_events applied last => wins
  }
}

// derivedStatusCode -> arabic (prefer customer_ar via arOf)
const byDerivedCode = {};
for (const e of master.derived_statuses || []) {
  const v = arOf(e);
  if (e.code && v) byDerivedCode[e.code] = v;
}

// exceptionCode / ancillaryDetails[].reason -> arabic
const byExceptionCode = {};
for (const list of [master.clearance_exceptions, master.delivery_exceptions, master.express_delivery_exceptions]) {
  for (const e of list || []) {
    const v = arOf(e);
    if (e.code && v && !(e.code in byExceptionCode)) byExceptionCode[e.code] = v;
  }
}

const fallbackAr = (master.fallback?.unknown_code?.arabic || 'تحديث جديد على الشحنة').trim();

const lit = (obj) =>
  '{\n' +
  Object.entries(obj)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n') +
  '\n}';

const out = `// AUTO-GENERATED by scripts/build-fedex-arabic.mjs
// Source: scripts/FedEx-mapping/fedex_master_mapping.json
// Do not edit by hand — edit the JSON and re-run:  node scripts/build-fedex-arabic.mjs
//
// Arabic labels for FedEx tracking statuses / exceptions. Used by
// components/shipping/Tracking.tsx (parseFedexJson) to translate the Tracking
// History when the site language is Arabic. English display is untouched, and
// any status not covered here keeps FedEx's own English text.
import type { Language } from '../../types';

const AR_BY_ENGLISH: Record<string, string> = ${lit(byEnglish)};

const AR_BY_EVENT_TYPE: Record<string, string> = ${lit(byEventType)};

const AR_BY_DERIVED_CODE: Record<string, string> = ${lit(byDerivedCode)};

const AR_BY_EXCEPTION_CODE: Record<string, string> = ${lit(byExceptionCode)};

/** Generic Arabic line for a status with no text at all (rare). */
export const FEDEX_FALLBACK_AR = ${JSON.stringify(fallbackAr)};

const norm = (s: string): string => s.normalize('NFKC').replace(/\\s+/g, ' ').trim().toLowerCase();

export interface FedexScanLike {
  eventType?: string;
  eventDescription?: string;
  derivedStatus?: string;
  derivedStatusCode?: string;
}

/**
 * Localized label for a FedEx scan event. \`en\` (or any non-'ar') returns FedEx's
 * own text unchanged. 'ar' tries: exact English phrase -> eventType code ->
 * derivedStatusCode -> (fall back to FedEx's English).
 */
export function fedexLabel(lang: Language, ev: FedexScanLike): string {
  const en = (ev.eventDescription || ev.derivedStatus || '').trim();
  if (lang !== 'ar') return en;
  return (
    (ev.eventDescription ? AR_BY_ENGLISH[norm(ev.eventDescription)] : undefined) ||
    (ev.eventType ? AR_BY_EVENT_TYPE[ev.eventType] : undefined) ||
    (ev.derivedStatusCode ? AR_BY_DERIVED_CODE[ev.derivedStatusCode] : undefined) ||
    en
  );
}

/**
 * Localized label for a FedEx clearance / delivery exception. 'ar' tries the
 * exception code, then the English phrase, then falls back to FedEx's text.
 */
export function fedexExceptionLabel(lang: Language, ex: { code?: string; description?: string }): string {
  const en = (ex.description || '').trim();
  if (lang !== 'ar') return en;
  return (
    (ex.code ? AR_BY_EXCEPTION_CODE[ex.code] : undefined) ||
    (ex.description ? AR_BY_ENGLISH[norm(ex.description)] : undefined) ||
    en
  );
}
`;

writeFileSync(OUT, out, 'utf8');
console.log(
  `[build-fedex-arabic] wrote ${OUT}\n` +
  `  AR_BY_ENGLISH: ${Object.keys(byEnglish).length}\n` +
  `  AR_BY_EVENT_TYPE: ${Object.keys(byEventType).length}\n` +
  `  AR_BY_DERIVED_CODE: ${Object.keys(byDerivedCode).length}\n` +
  `  AR_BY_EXCEPTION_CODE: ${Object.keys(byExceptionCode).length}`
);
